export type CharacterId = 'kairo' | 'reina' | 'razen' | 'shiro' | 'yuna' | 'ignis';

export type MoveKind = 'ATTACK_1' | 'ATTACK_2' | 'SKILL_1' | 'SKILL_2' | 'ULTIMATE';

export interface HitboxSpec {
  offsetX: number; // relative to character center in facing direction
  offsetY: number; // relative to feet (negative is up)
  width: number;
  height: number;
}

export interface MoveSpec {
  id: MoveKind;
  name: string;
  description: string;
  energyCost: number;
  cooldown: number; // seconds
  windupSec: number;
  activeSec: number;
  recoverySec: number;
  baseDamage: number;
  chipDamage: number;
  hitstunSec: number;
  blockstunSec: number;
  knockbackX: number;
  knockbackY: number;
  hitstopSec: number;
  screenShake: number;
  hitbox: HitboxSpec;
  lungeVx?: number;
  lungeVy?: number;
  projectile?: {
    speed: number;
    width: number;
    height: number;
    lifetime: number;
    style: 'slash_wave' | 'lightning_bolt' | 'shockwave' | 'ice_lance' | 'shadow_kunai' | 'solar_orb';
  };
}

export interface CharacterPalette {
  primary: string;
  secondary: string;
  accent: string;
  hair: string;
  skin: string;
  skinShadow: string;
  outline: string;
  energy: string;
  energyCore: string;
  eye: string;
}

export interface CharacterStats {
  maxHp: number;
  walkSpeed: number;
  runSpeed: number;
  jumpForce: number;
  weight: number; // higher = less knockback taken
  attackRating: number; // 1-10 display & multiplier
  speedRating: number; // 1-10 display
  defenseRating: number; // 1-10 display & damage reduction
}

export interface CharacterDefinition {
  id: CharacterId;
  name: string;
  title: string;
  archetype: string;
  bio: string;
  unlockRequirement: {
    level: number;
    arcadeWins: number;
    label: string;
  };
  hurtbox: {
    width: number;
    height: number;
  };
  stats: CharacterStats;
  palette: CharacterPalette;
  moves: Record<MoveKind, MoveSpec>;
}

